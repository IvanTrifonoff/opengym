export default function AdminHelp() {
  const nav = useNavigate()
  const [q, setQ] = useState('')
  const [open, setOpen] = useState({})
  const query = q.trim().toLowerCase()

  const toggle = id => setOpen(o => ({ ...o, [id]: !o[id] }))

  let shown = 0
  return <div className="narrow" style={{ paddingBottom: 40 }}>
    <div className="hdr">
      <button className="iconbtn" onClick={() => nav('/admin')} aria-label="Назад"><Icon name="chevronLeft" /></button>
      <div style={{ flex: 1 }}>
        <div className="small dim">ИмпульС</div>
        <h1 style={{ margin: 0 }}>Справка</h1>
        <div className="sub">Вопросы и ответы по всей системе</div>
      </div>
    </div>

    <div style={{ marginBottom: 12 }}><input className="field" placeholder="Поиск по вопросам…" value={q} onChange={e => setQ(e.target.value)} /></div>

    {FAQ.map(section => {
      const items = query ? section.items.filter(it => (it.q + ' ' + strip(it.a)).toLowerCase().includes(query)) : section.items
      if (!items.length) return null
      shown += items.length
      return <div key={section.sec} style={{ marginBottom: 6 }}>
        <h4 className="sec" style={{ marginTop: 16 }}>{section.sec}</h4>
        <div className="list" style={{ gap: 0 }}>
          {items.map(it => {
            const id = section.sec + '|' + it.q
            const isOpen = open[id]
            return <div key={id} className="item" style={{ cursor: 'pointer', flexDirection: 'column', alignItems: 'stretch', padding: 0 }} onClick={() => toggle(id)}>
              <div className="row between" style={{ padding: '13px 14px', gap: 10 }}>
                <div className="grow small" style={{ fontWeight: 600, lineHeight: 1.35 }}>{it.q}</div>
                <Icon name={isOpen ? 'chevronUp' : 'chevronDown'} style={{ color: 'var(--label-3)', marginTop: 2 }} />
              </div>
              {isOpen && <div className="muted small" style={{ padding: '0 14px 14px', lineHeight: 1.5 }}>{it.a}</div>}
            </div>
          })}
        </div>
      </div>
    })}
    {!shown && <div className="card empty">По запросу «{q}» ничего не найдено.</div>}
  </div>
}

function strip(node) {
  // crude text extraction for the search filter (React elements / strings)
  if (node == null) return ''
  if (typeof node === 'string' || typeof node === 'number') return String(node)
  if (Array.isArray(node)) return node.map(strip).join(' ')
  if (typeof node === 'object' && node.props) return strip(node.props.children)
  return ''
}
